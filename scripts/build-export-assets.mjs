import { mkdir, readFile, writeFile } from 'node:fs/promises';

// Keep portable presentations independent of the app, its host, and its bundler.
// The canonical JS/CSS sources are embedded as text at build time.
const sources = {
  motionSource: '../lib/buddy-motion.js',
  playbackSource: '../lib/offline-playback.js',
  studioCss: '../app/studio.css',
};
const declarations = await Promise.all(
  Object.entries(sources).map(async ([name, path]) => {
    const source = await readFile(new URL(path, import.meta.url), 'utf8');
    return `export const ${name} = ${JSON.stringify(source)};`;
  }),
);
const directory = new URL('../lib/generated/', import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(
  new URL('export-assets.ts', directory),
  `// Generated by scripts/build-export-assets.mjs. Do not edit.\n${declarations.join('\n')}\n`,
);
